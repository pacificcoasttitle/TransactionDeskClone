              <hr>
              <h3>The Process</h3>
              <ol>
              <li>We match author manuscript to three experts peer reviewer in a double blind approach and send them the final research protocol. A Pre-Submission (Peer) Review Proform accompanies the manuscript. </li>
<li>The peer reviewers conduct their review of the protocol and document their suggestion in the peer review proforma</li>
<li>Once completed, MyReposit returns the completed proforma to the author</li>
<li>Authors address reviewer comments and makes appropriate changes</li>
<li>Author submits manuscript to targeted journal describing expertise of the peer review in relation to the research and presents the completed proforma as evidence of independent peer review. It is mandatory for authors to highlight that comments and queries suggested by peer reviewers have been addressed and incorporated in the manuscript</li>
<li>MyReposit provides certificate of assurance that the peer review has been conducted by a person with appropriate expertise</li>
<li>Author submit the completed application and proforma to the targeted journal with their application for review and approval</li>
